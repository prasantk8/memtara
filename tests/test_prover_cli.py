def test_init_vault_writes_an_owner_only_file_and_reports_the_public_key(tmp_path):
    path = tmp_path / "vault.json"
    proc = run_cli(
        "init-vault", "--vault-path", str(path),
        "--income", "750000", "--liquid-assets", "2000000",
        "--risk-tolerance", "4", "--existing-holdings-value", "200000",
    )

    assert stat.S_IMODE(path.stat().st_mode) == 0o600, (
        "the file holds plaintext figures and a signing key; it must be created 0600, not "
        "created world-readable and chmod'ed afterwards"
    )
    assert "public key" in proc.stdout.lower()

    document = json.loads(path.read_text())
    assert set(document["figures"]) == set(vaultlib.FIGURE_NAMES)
    # The seed, not the post-cofactor scalar. Storing the scalar would invite
    # a reader to rebuild the keypair without the factor of 8 `eddsa_verify`
    # applies, producing signatures that fail inside the circuit with no
    # diagnostic beyond "unsatisfied constraint".
    assert int(document["signing_key_seed"], 16) < wc.SUBORDER


def test_a_world_readable_vault_is_refused_not_warned_about(tmp_path):
    path = tmp_path / "vault.json"
    run_cli("init-vault", "--vault-path", str(path), "--income", "1", "--liquid-assets", "1", "--risk-tolerance", "3")
    path.chmod(0o644)

    with pytest.raises(vaultlib.VaultError) as exc:
        vaultlib.load(path)
    assert "readable beyond its owner" in str(exc.value)
    # An escape hatch has to exist for disposable test data, or the check
    # becomes something people work around by deleting it.
    assert vaultlib.load(path, allow_insecure_permissions=True).wealth.income == 1


def test_a_mistyped_figure_name_is_refused_rather_than_defaulted(tmp_path):
    """The failure mode this catches is invisible otherwise.

    A vault carrying `liquid_asets` would load with `liquid_assets` absent,
    prove against zero, fail the liquidity limb, and tell the holder they are
    unsuitable — with nothing anywhere pointing at the typo.
    """
    path = tmp_path / "vault.json"
    path.write_text(
        json.dumps(
            {
                "version": 1,
                "signing_key_seed": format(7, "064x"),
                "figures": {"income": 1, "liquid_asets": 1, "risk_tolerance": 3, "existing_holdings_value": 0},
            }
        )
    )
    path.chmod(0o600)
    with pytest.raises(vaultlib.VaultError) as exc:
        vaultlib.load(path)
    assert "liquid_asets" in str(exc.value)


def test_an_off_scale_risk_tolerance_is_refused_at_the_vault(tmp_path):
    with pytest.raises(vaultlib.VaultError) as exc:
        vaultlib.create(tmp_path / "v.json", income=1, liquid_assets=1, risk_tolerance=9, existing_holdings_value=0)
    assert "1 and 5" in str(exc.value)


def test_a_seeded_vault_is_reproducible_and_an_unseeded_one_is_not(tmp_path):
    a = vaultlib.create(tmp_path / "a.json", income=1, liquid_assets=1, risk_tolerance=3, existing_holdings_value=0, seed=42)
    b = vaultlib.create(tmp_path / "b.json", income=1, liquid_assets=1, risk_tolerance=3, existing_holdings_value=0, seed=42)
    c = vaultlib.create(tmp_path / "c.json", income=1, liquid_assets=1, risk_tolerance=3, existing_holdings_value=0)
    assert a.keypair.public == b.keypair.public, "--seed exists so a demo can reproduce a client exactly"
    assert c.keypair.public != a.keypair.public, "the default must be fresh randomness"


def test_the_cli_refuses_to_open_an_assessment_without_an_org_key(tmp_path):
    """The deployment distinction, enforced rather than documented.

    An org API key can open an assessment against any of the bank's users, so
    a holder's device must not have one — and the error has to point at the
    mode that device should be using instead, or whoever hits it will simply
    put the org key on the phone.
    """
    path = tmp_path / "vault.json"
    run_cli("init-vault", "--vault-path", str(path), "--income", "1", "--liquid-assets", "1", "--risk-tolerance", "3")
    proc = run_cli(
        "--vault-path", str(path), "--user-id", str(uuid.uuid4()), "--product-isin", PRODUCT_ISIN,
        expect=1,
    )
    combined = proc.stdout + proc.stderr
    assert "org API key" in combined
    assert "--request-id" in combined, "the error must name the mode a device should use"


def test_resuming_a_request_requires_the_matching_request_file(tmp_path):
    path = tmp_path / "vault.json"
    run_cli("init-vault", "--vault-path", str(path), "--income", "1", "--liquid-assets", "1", "--risk-tolerance", "3")

    request_file = tmp_path / "request.json"
    request_file.write_text(json.dumps({"request_id": str(uuid.uuid4())}))
    proc = run_cli(
        "--vault-path", str(path), "--request-id", str(uuid.uuid4()),
        "--request-file", str(request_file), "--session-token", "irrelevant",
        expect=1,
    )
    assert "does not match" in proc.stdout + proc.stderr


