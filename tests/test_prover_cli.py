"""`memtara-prove` — the deployable device prover, end to end.

Two halves, deliberately separated:

  Offline    the vault file: what it refuses to load and why. No server, no
             toolchain, no Postgres. These run everywhere.

  Live       the actual journey — a real proof generated by the real Noir and
             Barretenberg toolchain, submitted to the real server, verified
             by real `bb verify`. Skips if any prerequisite is missing; CI
             fails the build if anything skipped (.github/workflows/ci.yml).

What this file is protecting is the claim on the tin: a bank can embed this
tool in an advisor terminal or a mobile app, and the client's four figures
never leave the device. So the tests assert on the *process boundary* — what
crosses the wire, what the exit code says, what the vault refuses — rather
than on the CLI's internals.

Run:
    DATABASE_URL=postgres://memtara:memtara@localhost:5433/memtara \\
    PATH="$HOME/.cargo/bin:$HOME/.bb:$HOME/.nargo/bin:$PATH" \\
    .venv/bin/python -m pytest tests/test_prover_cli.py -v
"""

from __future__ import annotations

