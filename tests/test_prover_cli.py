from conftest import CLIENTS_DIR, REPO_ROOT, db_connect

import wealth_client as wc

PROVE = REPO_ROOT / "clients" / "prover" / "memtara-prove"

PRODUCT_ISIN = "XS1234567890"
PRODUCT_NAME = "5-Year S&P Principal Protected Note"
MIN_INCOME = 500_000
MIN_LIQUIDITY = 1_000_000
MAX_CONCENTRATION = 30
RISK_LEVEL = 3

SUITABLE = dict(income=750_000, liquid_assets=2_000_000, risk_tolerance=4, existing_holdings_value=200_000)
#: Same client, one limb short: a risk tolerance of 2 against a level-3
#: product. Everything else clears comfortably, so the decline is
#: unambiguously attributable to one limb.
DECLINED = dict(SUITABLE, risk_tolerance=2)

sys.path.insert(0, str(CLIENTS_DIR))
from prover import vault as vaultlib  # noqa: E402
from prover.cli import EXIT_NOT_SUITABLE  # noqa: E402


def _hash_token(token: str) -> str:
    return base64.urlsafe_b64encode(hashlib.sha256(token.encode()).digest()).decode().rstrip("=")


def _b64url(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).decode().rstrip("=")


def run_cli(*args: str, expect: int | None = 0) -> subprocess.CompletedProcess:
    """Invoke the shim as a subprocess, the way a mobile app would.

    Not `main(argv)` in-process: the integration contract this tool sells is
    "spawn it and parse stdout", and an in-process call would not catch a
    stray `print` polluting the JSON, which is the failure that would actually
    break an embedder.
    """
    proc = subprocess.run(
        [sys.executable, str(PROVE), *args], capture_output=True, text=True, cwd=REPO_ROOT, timeout=300
    )
    if expect is not None and proc.returncode != expect:
        raise AssertionError(
            f"memtara-prove {' '.join(args)} exited {proc.returncode}, expected {expect}\n"
            f"--- stdout ---\n{proc.stdout}\n--- stderr ---\n{proc.stderr}"
        )
    return proc


